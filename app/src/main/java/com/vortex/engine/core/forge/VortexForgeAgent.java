    private static String applyByokCloudModel(GameProject p, String prompt, int providerIdx, String apiKey) throws Exception {
        String systemInst =
                "You are Vortex Forge AI inside Vortex Engine v4.0. Return ONLY valid JSON (no markdown fences) with keys: "
                + "{\"dimensionMode\":\"2D\"|\"3D\", \"scriptCode\":\"<ES6 JavaScript using vortex.joyX(), vortex.joyY(), vortex.setVel(name,vx,vy[,vz]), vortex.jump(name,imp), vortex.chaseTagAI(tag,target,spd), vortex.findNearestTag(from,tag), vortex.spawn2D(...), vortex.spawn3D(...), vortex.particles(...), vortex.playSound(...), vortex.addScore(n), vortex.setBanner(txt) with hooks onStart(), onUpdate(dt), onButton(btn), onCollide(a,b,tagA,tagB)>\", "
                + "\"addEntities\":[{\"name\":\"...\",\"tag\":\"player|enemy|coin|solid\",\"primitive\":\"CUBE|SPHERE|PYRAMID|RECT|CIRCLE\",\"x\":0,\"y\":1,\"z\":0,\"scaleX\":1,\"scaleY\":1,\"scaleZ\":1,\"colorHex\":\"#00E5FF\",\"bodyType\":\"DYNAMIC|STATIC|KINEMATIC\"}]}";

        String rawJson;
        if (providerIdx == 2) {
            // Google Gemini REST API
            String url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=" + apiKey;
            JSONObject body = new JSONObject();
            JSONArray contents = new JSONArray();
            JSONObject part = new JSONObject().put("text", systemInst + "\n\nUser Request: " + prompt);
            contents.put(new JSONObject().put("parts", new JSONArray().put(part)));
            body.put("contents", contents);
            String resp = postJson(url, null, body.toString());
            JSONObject rObj = new JSONObject(resp);
            rawJson = rObj.getJSONArray("candidates").getJSONObject(0)
                    .getJSONObject("content").getJSONArray("parts").getJSONObject(0).getString("text");
        } else {
            // OpenAI-compatible Chat Completions (Groq / OpenRouter / OpenAI)
            String endpoint = providerIdx == 1 ? "https://api.groq.com/openai/v1/chat/completions"
                    : providerIdx == 3 ? "https://openrouter.ai/api/v1/chat/completions"
                    : "https://api.openai.com/v1/chat/completions";
            String model = providerIdx == 1 ? "llama-3.3-70b-versatile"
                    : providerIdx == 3 ? "openai/gpt-4o-mini"
                    : "gpt-4o-mini";
            JSONObject body = new JSONObject();
            body.put("model", model);
            JSONArray msgs = new JSONArray();
            msgs.put(new JSONObject().put("role", "system").put("content", systemInst));
            msgs.put(new JSONObject().put("role", "user").put("content", prompt));
            body.put("messages", msgs);
            body.put("temperature", 0.3);
            String resp = postJson(endpoint, "Bearer " + apiKey, body.toString());
            JSONObject rObj = new JSONObject(resp);
            rawJson = rObj.getJSONArray("choices").getJSONObject(0).getJSONObject("message").getString("content");
        }

        rawJson = stripFences(rawJson);
        JSONObject parsed = new JSONObject(rawJson);
        if (parsed.has("dimensionMode")) p.dimensionMode = parsed.optString("dimensionMode", p.dimensionMode);
        if (parsed.has("scriptCode")) {
            p.scriptLanguage = "JS";
            p.scriptCode = parsed.optString("scriptCode", p.scriptCode);
        }
        JSONArray arr = parsed.optJSONArray("addEntities");
        int count = 0;
        if (arr != null) {
            for (int i = 0; i < arr.length(); i++) {
                JSONObject eo = arr.optJSONObject(i);
                if (eo != null) {
                    Entity ent = Entity.fromJson(eo);
                    ent.is3D = "3D".equalsIgnoreCase(p.dimensionMode);
                    p.entities.add(ent);
                    count++;
                }
            }
        }
        return "Forge BYOK Cloud Agent added " + count + " entities & updated ES6 JavaScript!";
    }

    private static String stripFences(String s) {
        String t = s.trim();
        if (t.startsWith("```")) {
            int nl = t.indexOf('\n');
            if (nl > 0) t = t.substring(nl + 1);
            if (t.endsWith("```")) t = t.substring(0, t.length() - 3);
        }
        return t.trim();
    }

    private static String postJson(String urlStr, String authHeader, String payload) throws Exception {
        HttpURLConnection conn = (HttpURLConnection) new URL(urlStr).openConnection();
        conn.setConnectTimeout(12_000);
        conn.setReadTimeout(25_000);
        conn.setRequestMethod("POST");
        conn.setDoOutput(true);
        conn.setRequestProperty("Content-Type", "application/json; charset=UTF-8");
        if (authHeader != null) conn.setRequestProperty("Authorization", authHeader);
        try (OutputStream os = conn.getOutputStream()) {
            os.write(payload.getBytes(StandardCharsets.UTF_8));
        }
        int code = conn.getResponseCode();
        InputStream is = (code >= 200 && code < 300) ? conn.getInputStream() : conn.getErrorStream();
        StringBuilder sb = new StringBuilder();
        if (is != null) {
            try (BufferedReader br = new BufferedReader(new InputStreamReader(is, StandardCharsets.UTF_8))) {
                String ln;
                while ((ln = br.readLine()) != null) sb.append(ln).append('\n');
            }
        }
        if (code < 200 || code >= 300) {
            throw new RuntimeException("HTTP " + code + ": " + sb.toString());
        }
        return sb.toString();
    }
